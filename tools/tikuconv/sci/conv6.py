"""批5-2：自然連連看 → 單選（不需要圖）

和社會的 conv5.py 同一個道理：這些題的「圖」其實是整題被排版成圖片，
題目文字（左欄項目、右欄選項）都在圖裡，讀圖抄下來就能轉成一題一問的單選題。
一對多的題改成反方向問，答案才唯一。
與其他題號內容完全相同的重複題（219/221/336/353/390/442/862/1310）不重複撰寫，
由 emit.py 的去重處理；1505001847 原檔沒有答案，不收。
"""
import json, collections
from convsci import SRC, lesson_of, sortkey, kps_of, tail, base

its = {i['no']: i for i in json.load(open('items.json'))}
out = []
used = collections.Counter()          # 同一題號拆成兩組問法時，序號要接著編

def cat(no, qtmpl, labels, pairs, why):
    it = its[no]
    les = lesson_of(it)
    seed = int(no[-2:])
    assert len(set(labels)) == len(labels) and 2 <= len(labels) <= 6, no
    for k, (name, li) in enumerate(pairs):
        sh = (seed + k) % len(labels)
        opts = labels[sh:] + labels[:sh]
        ai = (li - sh) % len(labels)
        o = base(it, les, '配對題', qtmpl.replace('＿', name), opts, ai,
                 '\n'.join(['✅ 正解：' + labels[li], '💡 ' + why] + tail(it, les)))
        o['id'] = o['id'] + '-m' + str(used[no] + k + 1)
        out.append(o)
    used[no] += len(pairs)


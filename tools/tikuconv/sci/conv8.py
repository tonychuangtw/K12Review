"""批5-4：自然「有圖的選擇題／是非題」→ 單選

這批原題雖然標記有圖，但圖多半只是把題目描述的東西畫出來（自製樂器、實驗裝置、路標），
題幹已經說明材料與做法，只要把圖上「看得到、但文字沒寫出來」的關鍵資訊補進題幹（例如
木片長短、四組裝置的差別、十字路口哪條路通往哪個方向），就能變成不用圖也答得出來的題。
真正需要靠圖判讀的（北斗七星第幾顆星）才配自繪 SVG。
內容完全重複的題號只寫一次（27/984、56/1417、81/1138、120/1071、177/1337、33/1682）。
"""
import json, collections
from convsci import SRC, lesson_of, sortkey, kps_of, tail, base

its = {i['no']: i for i in json.load(open('items.json'))}
out = []
used = collections.Counter()

def q(no, question, opts, ai, why, img=None):
    it = its[no]
    les = lesson_of(it)
    assert len(set(opts)) == len(opts) and 2 <= len(opts) <= 4, no
    used[no] += 1
    k = used[no]
    sh = ((int(no[-2:]) + k) % len(opts) - ai) % len(opts)
    if sh:
        opts = opts[-sh:] + opts[:-sh]
        ai = (ai + sh) % len(opts)
    exp = ([it['exp'].strip()] if it['exp'] else []) + ['✅ 正解：' + opts[ai], '💡 ' + why]
    o = base(it, les, '選擇題', question, opts, ai, '\n'.join(exp + tail(it, les)))
    o['id'] = o['id'] + '-p' + str(k)
    if img:
        o['img'] = img
    out.append(o)

def tf(no, stmt, ok, why):
    it = its[no]
    les = lesson_of(it)
    used[no] += 1
    exp = ['✅ 正解：' + ('○（敘述正確）' if ok else '╳（敘述不正確）'), '💡 ' + why]
    o = base(it, les, '是非題', '判斷對錯：' + stmt, ['○ 正確', '╳ 錯誤'], 0 if ok else 1,
             '\n'.join(exp + tail(it, les)))
    o['id'] = o['id'] + '-p' + str(used[no])
    out.append(o)


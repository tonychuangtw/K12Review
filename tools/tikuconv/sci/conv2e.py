"""自然批2c-2：開放式題組題 → 單選（題幹、誘答、解析逐題人工撰寫）

conv2d.py 只轉得動「子題自帶 ①②③④」的題組；這一支收的是要用寫的子題
（簡答、○╳ 判斷、填空），以及 conv2d 因為選項切壞而跳過的少數子題。
短文原文保留在題幹最前面（與 conv2d 一致），子題與選項人工撰寫。
"""
import json, re, collections
from convsci import SRC, lesson_of, sortkey, kps_of, tail, base

its = {i['no']: i for i in json.load(open('items.json'))}
out = []

def passage_of(no):
    """短文＝第一個子題編號之前的文字"""
    body = ' '.join(its[no]['body'])
    m = re.search(r'[（(][　\s]*[)）]\s*[（(]?\d|[　\s]1\s*[.、]', body)
    p = body[:m.start()].strip() if m else body.strip()
    return re.sub(r'\s+', ' ', p)

def q(no, k, question, opts, ai, why, qtype='題組題'):
    it = its[no]
    les = lesson_of(it)
    assert len(set(opts)) == len(opts) and 2 <= len(opts) <= 4, (no, opts)
    seed = int(no[-2:]) + k
    sh = (seed % len(opts) - ai) % len(opts)
    if sh:
        opts = opts[-sh:] + opts[:-sh]
        ai = (ai + sh) % len(opts)
    p = passage_of(no)
    o = base(it, les, qtype, (p + '\n' + question) if len(p) > 20 else question, opts, ai,
             '\n'.join(['✅ 正解：' + opts[ai], '💡 ' + why] + tail(it, les)))
    o['id'] = o['id'] + '-h' + str(k)
    out.append(o)

def tf(no, k, stmt, ok, fix):
    it = its[no]
    les = lesson_of(it)
    exp = ['✅ 正解：○（敘述正確）', '💡 這句話本身就是本課重點，記起來：' + stmt] if ok else \
          ['✅ 正解：╳（敘述不正確）', '💡 正確的說法是：' + fix]
    p = passage_of(no)
    o = base(it, les, '題組題', (p + '\n判斷對錯：' + stmt) if len(p) > 20 else '判斷對錯：' + stmt,
             ['○ 正確', '╳ 錯誤'], 0 if ok else 1, '\n'.join(exp + tail(it, les)))
    o['id'] = o['id'] + '-h' + str(k)
    out.append(o)


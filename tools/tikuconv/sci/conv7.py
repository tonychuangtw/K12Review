"""批5-3：需要看圖才答得出來的題 → 單選＋自繪 SVG 附圖

Tony 2026-08-19 定案：有圖的題要保留圖。做法分兩種：
  · 精確示意圖（太陽運行軌跡、月相、實驗裝置、折線圖）→ 自己畫 SVG 放在 img/sci/，
    生圖模型畫這種一定會把標示畫錯、中文字也會亂寫，不外包
  · 純情境插畫 → 另案用 gen-image.sh 重畫
題目 img 欄位放圖檔路徑，前端 renderFig() 會顯示並可點圖放大（test.js 會檢查檔案存在）。
第一批：太陽四季運行軌跡圖（img/sci/sun-seasons.svg），一張圖服務三個原題。
"""
import json, collections
from convsci import SRC, lesson_of, sortkey, kps_of, tail, base

its = {i['no']: i for i in json.load(open('items.json'))}
out = []
used = collections.Counter()

SUN = 'img/sci/sun-seasons.svg'

def q(no, img, question, opts, ai, why):
    it = its[no]
    les = lesson_of(it)
    assert len(set(opts)) == len(opts) and 2 <= len(opts) <= 4, no
    used[no] += 1
    k = used[no]
    seed = int(no[-2:]) + k
    sh = (seed % len(opts) - ai) % len(opts)
    if sh:
        opts = opts[-sh:] + opts[:-sh]
        ai = (ai + sh) % len(opts)
    o = base(it, les, '看圖題', question, opts, ai,
             '\n'.join(['✅ 正解：' + opts[ai], '💡 ' + why] + tail(it, les)))
    o['id'] = o['id'] + '-g' + str(k)
    o['img'] = img
    out.append(o)


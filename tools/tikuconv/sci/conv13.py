"""批5-9：自然「有圖的勾選題」第二批 → 單選

選項在題目文字裡的直接轉；選項只在圖裡但問的是課本概念的（防鏽方法、滅火原理、
折射現象的例子…），用同一個知識點自己寫成四選一。
「用仙后座找北極星」配自繪的 img/sci/cassiopeia.svg。
內容重複的題號只寫一次（193/1102、007/1166、035/555、148/698、174/1977、247/1447）。
"""
import json, collections
from convsci import SRC, lesson_of, sortkey, kps_of, tail, base

its = {i['no']: i for i in json.load(open('items.json'))}
out = []
used = collections.Counter()

def q(no, question, opts, ai, why, img=None):
    it = its[no]
    les = lesson_of(it)
    assert len(set(opts)) == len(opts) and 2 <= len(opts) <= 4, no
    used[no] += 1
    k = used[no]
    sh = ((int(no[-2:]) + k) % len(opts) - ai) % len(opts)
    if sh:
        opts = opts[-sh:] + opts[:-sh]
        ai = (ai + sh) % len(opts)
    o = base(it, les, '看圖題' if img else '勾選改單選', question, opts, ai,
             '\n'.join(['✅ 正解：' + opts[ai], '💡 ' + why] + tail(it, les)))
    o['id'] = o['id'] + '-k' + str(k)
    if img:
        o['img'] = img
    out.append(o)


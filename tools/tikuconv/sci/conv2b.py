"""自然批2b：填填看 → 單選（逐題人工撰寫，不可交 subagent）

原題型態很雜（分類填代號、○╳判斷、填空、排序），因此分三種產生器：
  cat(...)  分類題：一個原題產生多題「這一項屬於哪一類？」
  tf(...)   ○╳ 判斷：逐句轉是非題，錯的句子附正確說法
  one(...)  單題：填空／排序／情境題，選項與解析手寫
未收：有圖 35 題；1505000361、1505000243、1505000358 與其他題完全重複（同樣的問法已由別題涵蓋）。
"""
import json, collections
from convsci import SRC, lesson_of, sortkey, kps_of, tail, base

its = {i['no']: i for i in json.load(open('items.json'))}
out = []

def _mk(no, qtype, q, opts, ai, exp_body, suffix):
    it = its[no]
    les = lesson_of(it)
    assert len(set(opts)) == len(opts) and 2 <= len(opts) <= 4, (no, opts)
    o = base(it, les, qtype, q, opts, ai, '\n'.join(exp_body + tail(it, les)))
    o['id'] = o['id'] + suffix
    return o

def cat(no, qtmpl, labels, pairs, why=''):
    """分類題：pairs=[(項目, labels 的索引)]；選項順序依序輪轉，正解位置自然分散"""
    seed = int(no[-2:])
    for k, (name, li) in enumerate(pairs):
        sh = (seed + k) % len(labels)
        opts = labels[sh:] + labels[:sh]
        ai = (li - sh) % len(labels)
        exp = ['✅ 正解：' + labels[li]]
        if why:
            exp.append('💡 ' + why)
        out.append(_mk(no, '分類題', qtmpl.replace('＿', name), opts, ai, exp, '-c' + str(k + 1)))

def tf(no, rows):
    """○╳ 判斷：rows=[(敘述, 對錯, 錯的正確說法)]"""
    for k, (txt, ok, fix) in enumerate(rows):
        if ok:
            exp = ['✅ 正解：○（敘述正確）', '💡 這句話本身就是本課重點，記起來：' + txt]
        else:
            exp = ['✅ 正解：╳（敘述不正確）', '💡 正確的說法是：' + fix]
        out.append(_mk(no, '是非題', '判斷對錯：' + txt, ['○ 正確', '╳ 錯誤'], 0 if ok else 1, exp, '-t' + str(k + 1)))

def one(no, q, opts, ai, why, suffix=''):
    seed = int(no[-2:])
    sh = (seed % len(opts) - ai) % len(opts)
    if sh:
        opts = opts[-sh:] + opts[:-sh]
        ai = (ai + sh) % len(opts)
    out.append(_mk(no, '填空題', q, opts, ai, ['✅ 正解：' + opts[ai], '💡 ' + why], suffix))


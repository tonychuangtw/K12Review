"""批6-4：自然「當初跳過的無圖題」最後一批 —— 第4單元 燃燒與生鏽 29 個原題

改寫方式同前三批：四選一子題照原樣轉，複選／多小題改問「哪一項（哪一組）正確」，
開放式簡答改寫成單選、誘答自撰；原檔有詳解者把該子題原詳解放在解析最前面。
這批做完，五上社會／自然題本「當初跳過的無圖題」全數轉完。
"""
import json, collections
from convsci import SRC, lesson_of, sortkey, kps_of, tail, base

its = {i['no']: i for i in json.load(open('items.json'))}
out = []
used = collections.Counter()


def q(no, question, opts, ai, why, orig=None, qtype='活用'):
    it = its[no]
    les = lesson_of(it)
    assert len(set(opts)) == len(opts) and 2 <= len(opts) <= 4, no
    used[no] += 1
    k = used[no]
    sh = ((int(no[-2:]) + k) % len(opts) - ai) % len(opts)
    if sh:
        opts = opts[-sh:] + opts[:-sh]
        ai = (ai + sh) % len(opts)
    head = [orig.strip()] if orig else []
    o = base(it, les, qtype, question, opts, ai,
             '\n'.join(head + ['✅ 正解：' + opts[ai], '💡 ' + why] + tail(it, les)))
    o['id'] = o['id'] + '-y' + str(k)
    out.append(o)



"""批5-13：自然「有圖的看圖回答問題」→ 單選

把圖上的關鍵條件（裝置怎麼擺、紀錄表寫了什麼）寫進題幹後轉成四選一；
星空與太陽那幾題配已畫好的圖。內容與其他題號完全重複的不重複撰寫。
"""
import json, collections
from convsci import SRC, lesson_of, sortkey, kps_of, tail, base

its = {i['no']: i for i in json.load(open('items.json'))}
out = []
used = collections.Counter()
DIP = 'img/sci/big-dipper.svg'

def q(no, question, opts, ai, why, img=None):
    it = its[no]
    les = lesson_of(it)
    assert len(set(opts)) == len(opts) and 2 <= len(opts) <= 4, no
    used[no] += 1
    k = used[no]
    sh = ((int(no[-2:]) + k) % len(opts) - ai) % len(opts)
    if sh:
        opts = opts[-sh:] + opts[:-sh]
        ai = (ai + sh) % len(opts)
    o = base(it, les, '看圖題' if img else '問答題', question, opts, ai,
             '\n'.join(['✅ 正解：' + opts[ai], '💡 ' + why] + tail(it, les)))
    o['id'] = o['id'] + '-v' + str(k)
    if img:
        o['img'] = img
    out.append(o)


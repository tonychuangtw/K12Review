"""批5-5：自然「有圖的勾選題」→ 單選（第一批 12 個原題）

這些勾選題的選項文字就印在圖片裡（例：□甲.發抖　□乙.打電話），插圖只是把選項畫出來，
所以讀圖把選項抄下來就能變成純文字題。沿用批2a 的做法：複選改單選，
問「哪一項符合」或「哪一項不符合」，一個原題最多出 2 題。
剩下的勾選／活用題（約 90 個原題）依同一流程分批處理。
"""
import json, collections
from convsci import SRC, lesson_of, sortkey, kps_of, tail, base

its = {i['no']: i for i in json.load(open('items.json'))}
out = []
used = collections.Counter()

def q(no, question, opts, ai, why):
    it = its[no]
    les = lesson_of(it)
    assert len(set(opts)) == len(opts) and 2 <= len(opts) <= 4, (no, opts)
    used[no] += 1
    k = used[no]
    sh = ((int(no[-2:]) + k) % len(opts) - ai) % len(opts)
    if sh:
        opts = opts[-sh:] + opts[:-sh]
        ai = (ai + sh) % len(opts)
    exp = ([it['exp'].strip()] if it['exp'] else []) + ['✅ 正解：' + opts[ai], '💡 ' + why]
    o = base(it, les, '勾選改單選', question, opts, ai, '\n'.join(exp + tail(it, les)))
    o['id'] = o['id'] + '-s' + str(k)
    out.append(o)


import json, collections
from conv1 import SRC, lesson_of, sortkey
from conv3 import kps_of, tail

its = {i['no']: i for i in json.load(open('items.json'))}
out = []
used = collections.Counter()
MAP = 'img/social/taiwan-location.webp'
RIV = 'img/social/taiwan-rivers.webp'        # 有標名稱，當教學圖
RIVQ = 'img/social/taiwan-rivers-quiz.webp'  # 只有 1-4 編號，當判讀圖

def q(no, question, opts, ai, why, img=None):
    it = its[no]
    les = lesson_of(it)
    assert len(set(opts)) == len(opts) and 2 <= len(opts) <= 4, no
    used[no] += 1
    k = used[no]
    sh = ((int(no[-2:]) + k) % len(opts) - ai) % len(opts)
    if sh:
        opts = opts[-sh:] + opts[:-sh]
        ai = (ai + sh) % len(opts)
    o = {
        'id': 'oc' + no + '-t' + str(k), 'grade': 5, 'book': '五上', 'lesson': les,
        'tag': (kps_of(it)[0] if kps_of(it) else ''), 'diff': it['diff'],
        'qtype': '看圖題' if img else '題組題',
        'q': question, 'options': opts, 'answer': ai,
        'exp': '\n'.join(['✅ 正解：' + opts[ai], '💡 ' + why] + tail(it, les)), 'src': SRC[it['cat']],
    }
    if img:
        o['img'] = img
    out.append(o)


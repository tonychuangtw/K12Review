"""批5-2：社會「有圖但情境寫在題目文字裡」的題 → 單選（不需要圖）

這批原題雖然有插圖，但題幹已經把情境、圖片內容描述完整（照片拍到什麼、故事發生什麼），
選項也在文字裡，只要把「如上圖」「圖片中」這類指涉改寫掉，就是不用圖也答得出來的題。
真正要靠圖判讀的（地圖代號、示意圖位置、生活足跡表）留到後續配自繪 SVG 處理。
"""
import json, collections
from conv1 import SRC, lesson_of, sortkey
from conv3 import kps_of, tail

its = {i['no']: i for i in json.load(open('items.json'))}
out = []
used = collections.Counter()

def q(no, question, opts, ai, why):
    it = its[no]
    les = lesson_of(it)
    assert len(set(opts)) == len(opts) and 2 <= len(opts) <= 5, no
    used[no] += 1
    k = used[no]
    sh = ((int(no[-2:]) + k) % len(opts) - ai) % len(opts)
    if sh:
        opts = opts[-sh:] + opts[:-sh]
        ai = (ai + sh) % len(opts)
    exp = ([it['exp'].strip()] if it['exp'] else []) + ['✅ 正解：' + opts[ai], '💡 ' + why]
    out.append({
        'id': 'oc' + no + '-g' + str(k), 'grade': 5, 'book': '五上', 'lesson': les,
        'tag': (kps_of(it)[0] if kps_of(it) else ''), 'diff': it['diff'], 'qtype': '選擇題',
        'q': question, 'options': opts, 'answer': ai,
        'exp': '\n'.join(exp + tail(it, les)), 'src': SRC[it['cat']],
    })

def tf(no, stmt, ok, why):
    it = its[no]
    les = lesson_of(it)
    used[no] += 1
    exp = ['✅ 正解：' + ('○（敘述正確）' if ok else '╳（敘述不正確）'), '💡 ' + why]
    out.append({
        'id': 'oc' + no + '-g' + str(used[no]), 'grade': 5, 'book': '五上', 'lesson': les,
        'tag': (kps_of(it)[0] if kps_of(it) else ''), 'diff': it['diff'], 'qtype': '是非題',
        'q': '判斷對錯：' + stmt, 'options': ['○ 正確', '╳ 錯誤'], 'answer': 0 if ok else 1,
        'exp': '\n'.join(exp + tail(it, les)), 'src': SRC[it['cat']],
    })


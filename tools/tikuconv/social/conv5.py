its = {i['no']: i for i in json.load(open('items.json'))}
out = []

def cat(no, qtmpl, labels, pairs, why):
    """qtmpl 裡的 ＿ 會換成項目名稱；選項順序逐題輪轉，正解位置自然分散"""
    it = its[no]
    les = lesson_of(it)
    seed = int(no[-2:])
    assert len(set(labels)) == len(labels) and 2 <= len(labels) <= 5, no
    for k, (name, li) in enumerate(pairs):
        sh = (seed + k) % len(labels)
        opts = labels[sh:] + labels[:sh]
        ai = (li - sh) % len(labels)
        out.append({
            'id': 'oc' + no + '-' + str(k + 1), 'grade': 5, 'book': '五上', 'lesson': les,
            'tag': (kps_of(it)[0] if kps_of(it) else ''), 'diff': it['diff'], 'qtype': '配對題',
            'q': qtmpl.replace('＿', name), 'options': opts, 'answer': ai,
            'exp': '\n'.join(['✅ 正解：' + labels[li], '💡 ' + why] + tail(it, les)),
            'src': SRC[it['cat']],
        })


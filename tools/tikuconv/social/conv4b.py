its = {i['no']: i for i in json.load(open('items.json'))}

def norm_q(it):
    q = ' '.join(it['body']).strip()
    # 先把各種空格佔位換成 sentinel，才不會被後面的空白正規化吃掉
    q = re.sub(r'[（(]\s*[　\s]{2,}\s*[)）]', '\x00', q)
    q = re.sub(r'[_＿]{2,}', '\x00', q)
    q = re.sub(r'\s+', ' ', q).strip()
    q = q.replace('\x00', '（　　）')
    n = q.count('（　　）')
    lead = '依序選出最適合填入空格的答案：' if n > 1 else '選出最適合填入空格的答案：'
    return lead + q, n

def mk(no, opts, ai, why):
    it = its[no]
    les = lesson_of(it)
    q, n = norm_q(it)
    assert len(opts) == 4 and len(set(opts)) == 4, no
    # 手寫時正解多半擺在第一個，這裡依題號決定性地旋轉，讓正解位置分散（選項內容不變）
    shift = (int(no[-2:]) % 4 - ai) % 4
    opts = opts[-shift:] + opts[:-shift] if shift else opts
    ai = (ai + shift) % 4
    exp = ['✅ 正解：' + opts[ai], '💡 ' + why]
    return {'id': 'o' + no, 'grade': 5, 'book': '五上', 'lesson': les,
            'tag': (kps_of(it)[0] if kps_of(it) else ''), 'diff': it['diff'], 'qtype': '填空題',
            'q': q, 'options': opts, 'answer': ai,
            'exp': '\n'.join(exp + tail(it, les)), 'src': SRC[it['cat']]}

